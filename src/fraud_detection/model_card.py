"""Render a model card (markdown) from the training report. Every number comes from the run."""

from __future__ import annotations

from typing import Any

PRETTY = {
    "logistic_regression": "Logistic regression (linear)",
    "spline_logistic_regression": "Logistic regression (spline / additive)",
    "hist_gradient_boosting": "HistGradientBoosting",
}


def _pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def _money(x: float) -> str:
    return f"{x:,.0f}"


def render_model_card(report: dict[str, Any]) -> str:
    data, cfg = report["data"], report["config"]
    champion = report["model_name"]
    b = data["boundaries"]
    lines: list[str] = [
        f"# Model card: {report['model_version']}",
        "",
        "_Generated by `fraud-ml train` from the metrics of this run. Do not edit by hand._",
        "",
        "## Model details",
        "",
        f"- **Selected model**: {PRETTY.get(champion, champion)} (`{champion}`), chosen by "
        "validation PR-AUC.",
        f"- **Version**: `{report['model_version']}` (hash of model parameters, feature/split "
        "config and training-data fingerprint)",
        f"- **Trained**: {report['created_at']}",
        f"- **Imbalance handling**: positive-class weight {cfg['positive_weight']:g}",
        f"- **Features** ({len(report['feature_names'])}): "
        + ", ".join(f"`{f}`" for f in report["feature_names"]),
        "",
        "## Intended use",
        "",
        "Ranking card transactions for manual review in a demo setting. The model is trained on "
        "**synthetic** data produced by this repository's generator; it has never seen real "
        "transactions and must not be used to make decisions about real people or payments.",
        "",
        "## Data",
        "",
        f"Synthetic log of {data['transactions']:,} transactions (fingerprint "
        f"`{data['fingerprint']}`), split by time; the first "
        f"{cfg['split']['burn_in_days']} days are burn-in for history features.",
        "",
        "| split | period | rows | frauds | fraud rate |",
        "|---|---|---:|---:|---:|",
    ]
    periods = {
        "train": (b["train_start"], b["validation_start"]),
        "validation": (b["validation_start"], b["test_start"]),
        "test": (b["test_start"], b["data_end"]),
    }
    for split, (lo, hi) in periods.items():
        rows, frauds = data["rows"][split], data["frauds"][split]
        rate = f"{100 * frauds / rows:.2f}%"
        lines.append(f"| {split} | {lo} to {hi} | {rows:,} | {frauds} | {rate} |")

    lines += [
        "",
        "## Ranking metrics",
        "",
        "| model | split | PR-AUC | ROC-AUC | recall@P≥80% | recall@P≥90% | P@50 | P@100 | P@500 |",
        "|---|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for name, by_split in report["models"].items():
        for split in ("validation", "test"):
            m = by_split[split]
            marker = " **(selected)**" if name == champion and split == "test" else ""
            lines.append(
                f"| {PRETTY.get(name, name)}{marker} | {split} | {m['pr_auc']:.3f} | "
                f"{m['roc_auc']:.4f} | {_pct(m['recall_at_precision_80'])} | "
                f"{_pct(m['recall_at_precision_90'])} | {m['precision_at_50']:.2f} | "
                f"{m['precision_at_100']:.2f} | {m['precision_at_500']:.2f} |"
            )
    lines += [
        "",
        "`recall@P≥x` is read off each split's own precision-recall curve (an upper bound for a "
        "deployed threshold); the operating points below use thresholds fixed on validation.",
        "",
        "## Operating points (selected model, thresholds chosen on validation)",
        "",
        f"Cost model: each alert costs {cfg['review_cost']:g} (review effort), each missed fraud "
        "costs its full amount.",
        "",
        "| policy | split | threshold | alerts | TP | FP | FN | precision | recall | cost |",
        "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for policy, by_split in report["operating_points"].items():
        for split in ("validation", "test"):
            o = by_split[split]
            lines.append(
                f"| {policy} | {split} | {o['threshold']:.4f} | {o['alerts']} | "
                f"{o['true_positives']} | {o['false_positives']} | {o['false_negatives']} | "
                f"{_pct(o['precision'])} | {_pct(o['recall'])} | {_money(o['cost'])} |"
            )
    base = report["cost_baselines"]
    lines += [
        "",
        f"Test-period reference costs: no model (every fraud is lost) "
        f"{_money(base['no_model_cost'])}; review every transaction "
        f"{_money(base['review_everything_cost'])}.",
        "",
        "## Permutation importance (validation, drop in average precision)",
        "",
        "| feature | mean | std |",
        "|---|---:|---:|",
    ]
    for row in report["permutation_importance"][:12]:
        lines.append(f"| `{row['feature']}` | {row['mean']:.4f} | {row['std']:.4f} |")
    lines += [
        "",
        "Correlated features (for example the different velocity windows) share credit, so a "
        "low score does not mean a feature carries no information.",
        "",
        "## Limitations and risks",
        "",
        "- Synthetic data: the fraud patterns are the ones the generator injects, so the model "
        "is evaluated on patterns it could in principle learn perfectly. Real fraud adapts.",
        "- Labels are assumed complete after the label delay "
        f"({cfg['features']['label_delay_seconds'] // 86400} days); real chargebacks trickle in "
        "for weeks and some fraud is never reported.",
        "- Scores are not calibrated probabilities (class weighting shifts them); use the "
        "threshold shipped with the artefact, or recalibrate before reading them as rates.",
        "- Hour-of-day uses UTC, not the cardholder's local time.",
        "- Country and device signals can encode protected characteristics in real data and "
        "need a fairness review before any real use.",
        "",
    ]
    return "\n".join(lines)
